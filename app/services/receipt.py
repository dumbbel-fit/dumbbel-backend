"""Receipt PDF (spec §9): gym name, GSTIN, receipt no, member, plan, amount in words, method, reference, recorded by."""
import io

from reportlab.lib.pagesizes import A5
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfgen import canvas


def _money(paise: int) -> str:
    from app.utils import rupees
    return rupees(paise).replace("₹", "Rs. ")  # built-in PDF fonts lack the ₹ glyph


def render_receipt_pdf(d: dict) -> bytes:
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A5)
    w, h = A5
    x, y = 14 * mm, h - 18 * mm

    def line(label, value, bold=False):
        nonlocal y
        c.setFont("Helvetica", 9)
        c.setFillGray(0.4)
        c.drawString(x, y, label)
        c.setFillGray(0)
        c.setFont("Helvetica-Bold" if bold else "Helvetica", 10)
        c.drawString(x + 38 * mm, y, str(value or "—")[:70])
        y -= 7 * mm

    c.setFont("Helvetica-Bold", 14)
    c.drawString(x, y, (d["gym"]["name"] or "")[:60])
    y -= 6 * mm
    c.setFont("Helvetica", 9)
    addr = ", ".join(p for p in [d["gym"].get("address_line"), d["gym"].get("area"), d["gym"].get("city"),
                                  d["gym"].get("pincode")] if p)
    if addr:
        c.drawString(x, y, addr[:95])
        y -= 5 * mm
    if d["gym"].get("gstin"):
        c.drawString(x, y, f"GSTIN: {d['gym']['gstin']}")
        y -= 5 * mm
    y -= 3 * mm
    c.setFont("Helvetica-Bold", 12)
    c.drawString(x, y, "PAYMENT RECEIPT" + ("  (VOID)" if d["status"] == "voided" else ""))
    y -= 9 * mm
    line("Receipt no", d["receipt_no"], True)
    line("Date", d["paid_at_local"])
    line("Member", f"{d['member']['name']} ({d['member']['member_code']})")
    line("Plan", d.get("plan_name"))
    line("Amount", _money(d["amount_paise"]), True)
    c.setFont("Helvetica-Oblique", 9)
    c.drawString(x, y, d["amount_in_words"][:95])
    y -= 8 * mm
    line("Method", d["method"].upper())
    line("Reference", d.get("reference"))
    line("Recorded by", d.get("recorded_by"))
    if d["status"] == "voided":
        line("Voided", d.get("void_reason"))
    y -= 4 * mm
    c.setFont("Helvetica", 8)
    c.setFillGray(0.4)
    footer = d.get("footer") or ""
    if footer:
        c.drawString(x, y, footer[:110])
        y -= 5 * mm
    c.drawString(x, 10 * mm, "Generated by DUMBBEL.fit")
    c.showPage()
    c.save()
    return buf.getvalue()


